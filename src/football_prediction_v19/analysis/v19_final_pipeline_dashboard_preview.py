# -*- coding: utf-8 -*-
"""Final pipeline dashboard writer."""
from __future__ import annotations

from pathlib import Path


def write_final_pipeline_dashboard(output_path: str | Path, *, input_mode: str, release_status: str, batch_os: dict[str, object], health: dict[str, object], readiness: dict[str, object], artifact_paths: dict[str, str]) -> str:
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join([
        "# v1.9 Final Pipeline Preview Dashboard",
        "",
        "## 1. Final Pipeline Status",
        "- v19_final_pipeline_status: V19_FINAL_PIPELINE_PREVIEW_READY",
        f"- input mode: {input_mode}",
        f"- release readiness status: {release_status}",
        f"- batch OS status: {batch_os.get('batch_os_status', '')}",
        "- safety status: network_calls_enabled=false; betting_logic_enabled=false; staking_logic_enabled=false; roi_logic_enabled=false",
        "",
        "## 2. What This Pipeline Can Do",
        "- Single Match Excel Intake",
        "- Raw Evidence Intake",
        "- Match Pack Auto Assembly",
        "- Match Pack Scan",
        "- Auto Batch Config",
        "- Batch Health Gate",
        "- Evidence Coverage Matrix",
        "- Batch OS",
        "- Completion Campaign",
        "- Portfolio Delta",
        "- Scenario Batch Lab",
        "- Final Action Plan",
        "",
        "## 3. Input Summary",
        f"- input_mode: {input_mode}",
        f"- packs_total: {health.get('packs_total', 'n/a')}",
        "",
        "## 4. Match / Portfolio Summary",
        f"- matches_total: {batch_os.get('matches_total', 0)}",
        f"- matches_succeeded: {batch_os.get('matches_succeeded', 0)}",
        f"- matches_failed: {batch_os.get('matches_failed', 0)}",
        f"- average readiness delta: {batch_os.get('average_readiness_delta', 0)}",
        "",
        "## 5. Evidence Health Summary",
        f"- packs ready: {health.get('packs_ready', 0)}",
        f"- packs partial: {health.get('packs_partial', 0)}",
        f"- packs blocked: {health.get('packs_blocked', 0)}",
        "- common missing groups: recent_form, big_chances, availability, opening_closing_odds, dnb_ou_market",
        "",
        "## 6. Completion Summary",
        f"- fillable_fields_total: {batch_os.get('fillable_fields_total', 0)}",
        f"- critical_fields_total: {batch_os.get('critical_fields_total', 0)}",
        f"- master completion template path: {batch_os.get('master_completion_template_path', '')}",
        "",
        "## 7. Delta Summary",
        f"- candidate_count_delta: {batch_os.get('candidate_count_delta', 0)}",
        f"- average_readiness_delta: {batch_os.get('average_readiness_delta', 0)}",
        f"- filled_values_count: {batch_os.get('filled_values_count', 0)}",
        "",
        "## 8. Release Readiness Summary",
        f"- checks passed: {readiness.get('checks_passed', 0)}",
        f"- checks failed: {readiness.get('checks_failed', 0)}",
        f"- recommendation: {readiness.get('recommendation', '')}",
        "",
        "## 9. What To Do Next",
        "- Fill missing critical fields",
        "- Rerun completion",
        "- Review portfolio delta",
        "- Add missing evidence groups",
        "- Do not use for production betting",
        "",
        "## 10. Artifact Links",
        *[f"- {name}: {value}" for name, value in artifact_paths.items()],
        "",
        "## 11. Safety Footer",
        "No production betting. No stake. No ROI. No automatic betting. No external network calls.",
        "",
    ])
    path.write_text(text, encoding="utf-8")
    return str(path.resolve())
